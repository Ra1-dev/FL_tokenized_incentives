"""Generate the predeclared evaluation and statistical protocol."""

from fractions import Fraction
from pathlib import Path

from evaluation import ABLATIONS, evaluation_cells, read, scenario_key
from fltoken.io import sha256, write_json


def main():
    plan = read("configs/evaluation_plan.json")
    cells = list(evaluation_cells(plan))
    distinct = {scenario_key(cell) for cell in cells if cell["horizon"] == "main"}
    count = len(plan["seeds"])
    design = dict(plan=plan, plan_sha256=sha256("configs/evaluation_plan.json"),
                  main_runs=sum(cell["horizon"] == "main" for cell in cells),
                  long_runs=sum(cell["horizon"] == "long" for cell in cells),
                  distinct_main_scenarios=len(distinct), attack_scenarios=sum(attack != "none" for attack,_ in distinct),
                  seeds=count, bootstrap_samples=plan["statistics"]["bootstrap_resamples"],
                  minimum_seed_p=float(Fraction(2,2**count)),
                  comparison_family=len(plan["statistics"]["primary_metrics"])*3,
                  ablations=ABLATIONS, status="predeclared; evaluation results pending")
    write_json("results/evaluation/design.json", design)
    summary = read("results/summary.json")
    summary["evaluation_design"] = design
    write_json("results/summary.json",summary)
    design = read("results/summary.json")["evaluation_design"]
    p = design["plan"]
    text = f"""# Evaluation and uncertainty

Status: **{design['status']}**. Generated by `python scripts/document_evaluation.py`
from `results/summary.json`; the executable plan is `configs/evaluation_plan.json`.

## Coverage and publication boundary

The main comparison contains {design['main_runs']} complete Flower runs over
seeds {p['seeds']}: attack-free once per seed; each single attack at fractions
{p['fractions']}; and the fixed Sendros mixture once per seed. Each lasts
{p['rounds']} rounds. A further {design['long_runs']}
mixture runs last {p['long_run']['rounds']} rounds and are analyzed separately.
Every rule and component stage scores the same update matrix in a run; scoring
does not change FedAvg or the model's training trajectory.

Every run retains its full update matrices under the ignored `results/cache/`
directory. The grid runner verifies matrix hashes and sampled client order
against the participation log. Later reward rules are scored offline on these
same matrices, without retraining. Keep this cache when moving or resuming runs.

Before execution, publish the complete pilot evidence and selected method.
`run_grid.py` compares the frozen configuration, its source bindings, selection
summary, pilot records and candidate evidence with `origin/main`. Unpublished
or edited artifacts fail the gate. The per-run entry point also checks the
published freeze and its scientific bindings before constructing any method
scorer. Synthetic tests exercise the implementation without empirical evaluation.
The grid runner reconstructs the complete pilot candidate comparison from its
recorded qualities and checks publication equality again before starting runs.

```bash
python scripts/run_grid.py
python scripts/run_grid.py --no-run
python scripts/summarize_grid.py
```

The first command currently requires the pending pilot freeze. Resumption only
accepts completed cells whose resolved configuration, method digest, source
hashes and reconstructed ledger match. The manifest records every completed
cell and total measured training wall time. Failed or missing cells cannot
be silently omitted from the analysis.

Run the training command and its `--no-run` cache validation in the same pinned
training checkout. That validation deliberately requires unchanged local training
sources and retained matrices. For a later clean checkout containing completed
result artifacts, use `summarize_grid.py`: it verifies each recorded training
source against its published historical commit, rather than treating the latest
working tree as the source of an older experiment. It also reconstructs integer
ledgers and checks complete coverage without needing the ignored raw cache.

Historical source verification reads the analysis checkout's own Git objects,
independent of the caller's working directory and inherited Git location settings.
Failed Git operations retain their exit status and diagnostic. Keep the recorded
training history available locally; a shallow clone may need
`git fetch --unshallow origin` before analysis.

Some freezes also bind runner and validation programs. Use the
[pinned calibration checkout](../README.md#pinned-calibration-checkout) to execute
the existing extension comparison when current analysis code has changed.
Document generation can verify recorded producer bytes in their published history;
this does not relax the current-source checks required to execute a frozen method.

The persistent `results/grid/execution.json` clock starts before the first
training attempt and closes after complete validation. Its elapsed wall time
includes failed attempts, restarts and intervening downtime. The sum of successful
run times is reported separately. Preserve this clock with the grid artifacts;
validation-only runs retain its original endpoints and cannot create a missing
completion time. Wall time is an observed runtime measurement, not a number
expected to repeat identically on a different machine.

## Component comparison

Mstar uses all components and the pilot-selected numerical parameters. Aref forces
only the excluding reference on; Aema adds reputation; Afull adds penalties.
Each has independent client state and retains the selected numerical values,
including values for components disabled in an ablation. The fully enabled
stage equals Mstar; the analysis rejects any mismatch. There is no
parameter search for an ablation stage. Immediate minted rewards and subsequent
stake loss, burns, locked rewards and claims are separate outcomes.

Multi-Krum receives the known population attacker fraction to set its declared
nominal fault budget, a favorable information assumption. This is not the realized
attacker count in each sampled round: uniform sampling can exceed that budget.
The budget is not retuned from observed adversary identities. Its selected set
determines shadow rewards only, so an aggregation robustness guarantee is not
claimed for this comparison.

## Seed uncertainty and undefined values

The experimental unit is the complete seed. For each cell and each scalar
metric, report the mean, sample standard deviation and a
{p['statistics']['confidence']:.0%} percentile bootstrap interval. Draw
{design['bootstrap_samples']} ordered seed resamples with replacement using
Python Random MT19937 and fixed seed {p['statistics']['bootstrap_seed']}, grouping
identical index multisets for efficiency. Rational sample means and linear
empirical-quantile interpolation give reproducible output. Finite resampling
still introduces Monte Carlo error. This is a percentile interval, not a bias-corrected
interval; a small seed sample can give unstable or degenerate uncertainty and
does not justify a population-wide guarantee.

Undefined metrics retain explicit counts. If any planned seed is undefined,
the corresponding mean interval and paired claim are undefined. No empty-reward
attacker share is imputed for evaluation. The pilot selection cost is a separate,
predeclared optimization convention. Detection metrics retain their recorded
zero-denominator convention rather than being silently redefined here.

For pooled summaries, average the fixed scenarios within each seed, then
bootstrap the complete seed means. Paired difference intervals use common seed
indices across rules. Client participations are not
additional independent seed observations.

## Paired comparisons and multiplicity

The fixed mixture and attack-free setups are each executed once per seed.
The main grid contains {design['distinct_main_scenarios']} distinct scenarios;
attacked-condition comparisons use the
{design['attack_scenarios']} attack-present scenarios.

For each primary outcome, compare Mstar with each baseline using a two-sided
conditional Wilcoxon signed-rank test on all
{design['attack_scenarios']*design['seeds']} attacked condition-seed pairs.
Discard exact zero differences, assign average ranks to tied magnitudes,
and compute the sign-randomization distribution exactly. Differences between
recorded floating values are computed as exact rational differences, without
an adaptive tie tolerance. An all-zero comparison has p-value unity.

Apply Holm adjustment to one family of {design['comparison_family']} primary
contrasts across attacker share and honest false penalties. An undefined test
keeps its place in that family; removing it must not make another result more
significant. Also report a separately labelled family of paired tests on the
complete seed-level pooled differences. With {design['seeds']} nonzero pairs,
its smallest two-sided exact p-value is {design['minimum_seed_p']}.
Seed-level and per-condition tests are descriptive supplements; the primary
pairing unit remains the attacked condition-seed pair.

Report the mean paired difference and matched-pairs rank-biserial effect size;
negative values favor Mstar for these cost metrics. The conditional signed-rank
null assumes independently exchangeable signs and a symmetric difference
distribution. Conditions sharing seeds are dependent; the condition-seed
p-values describe this fixed design and cannot establish
independent evidence from a broader population. Report both analyses and their
paired effect intervals, including negative or inconclusive results. Long runs
never increase the main comparison's sample count.

The statistical conventions follow the definitions and cautions in the official
[Wilcoxon documentation](https://docs.scipy.org/doc/scipy/reference/generated/scipy.stats.wilcoxon.html)
and [bootstrap documentation](https://docs.scipy.org/doc/scipy/reference/generated/scipy.stats.bootstrap.html).
The implementation enumerates the conditional tied-rank null directly instead
of relying on a library's untied exact-table shortcut.

## Generated comparison assets

After the complete grid summary exists, run `python scripts/make_macros.py`,
`python scripts/make_tables.py` and `python scripts/make_figures.py`.
All comparison assets use the `evaluation` record in `results/summary.json`.
Per-condition tables retain every rule's mean, sample SD and interval;
pooled tables average within seed before resampling. Attacker-share pooling
uses attacked conditions, while honest-cost pooling includes the attack-free
condition. The paired tables use attacked conditions for both costs.
Each table states the common training device. Undefined estimates remain
explicitly undefined rather than disappearing from the display.

The wide `evaluation_paired.tex` table reports condition--seed tests;
`evaluation_paired_seed.tex` reports the separately adjusted seed-pooled tests.
Both identify their pairing unit and report pair counts, signed differences,
rank effects, raw p-values and Holm-adjusted p-values. The wide
`evaluation_paired_intervals.tex` table reports paired seed means, sample SD,
bootstrap limits and defined/missing seed counts. Negative differences favor
Mstar for both costs. Undefined comparisons never acquire a zero effect or a
unit p-value merely for display.

Contrast macros use `Evaluation`, the outcome (`AttackerShare` or
`HonestPenalty`), the baseline (`Equal`, `Cosine` or `Krum`), and a suffix.
`DifferenceMean`, `DifferenceSD`, `DifferenceLow` and `DifferenceHigh` are
percentage points; `PairedDefined` and `PairedMissing` count seeds.
`ConditionSeed` and `Seed` identify each test family before `Pairs`, `P`,
`RankEffect` or `HolmP`. The values come from the recorded contrast, with no
additional testing or resampling during export.

Attacker-share and false-penalty plots use a single-column width. The ablation
and main accuracy panels use double-column width; the long-run accuracy curve
is separate. Accuracy and loss histories must match the common participation
log and its recorded hashes before aggregation. Accuracy curves describe the
shared FedAvg trajectory and cannot attribute an accuracy gain to a shadow
reward rule. Figure error bands show seed bootstrap intervals, not independent
client or round uncertainty. The generated numeric macro names remain stable
as measurements are refreshed.
"""
    if Path("configs/method_frozen.json").exists():
        text = text.replace("The first command currently requires the pending pilot freeze.",
                            "The first command requires the published pilot freeze and its complete evidence.")
    Path("docs/EVALUATION.md").write_text(text,encoding="utf-8",newline="\n")
    print(f"Declared {design['main_runs']} main and {design['long_runs']} long runs; evaluation results pending")


if __name__ == "__main__":
    main()
