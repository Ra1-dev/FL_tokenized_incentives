"""Render verified reading notes without claiming unread sources."""

import json
from pathlib import Path
import re


def main():
    entries = json.loads(Path("results/literature/annotations.json").read_text(encoding="utf-8"))
    bibtex_keys = re.findall(r"(?m)^@\w+\{([^,]+),", Path("paper/references.bib").read_text(encoding="utf-8"))
    cited = [entry["bibtex_key"] for entry in entries]
    if len(set(bibtex_keys)) != len(bibtex_keys) or len(set(cited)) != len(cited) or set(cited) != set(bibtex_keys):
        raise ValueError("reading manifest and BibTeX entries must match uniquely")
    lines = ["# Annotated bibliography", "", "Generated by `python scripts/document_bibliography.py` from the source-reading manifest.",
             f"Current verified entries: {len(entries)}. This working bibliography is incomplete.", "",
             "| Source | Problem | Method | Data | Finding | What it does not do | Use in this project |", "|---|---|---|---|---|---|---|"]
    for e in entries:
        label = f"[{e['authors']} ({e['year']}), {e['title']}]({e['url']})"
        lines.append("| " + " | ".join([label] + [e[k] for k in ["problem", "method", "data", "finding", "missing", "use"]]) + " |")
    lines += ["", "## Reading and metadata provenance", ""]
    for e in entries:
        lines.append(f"- **{e['key']}**: cite as `{e['bibtex_key']}`. {e['read']} Venue: {e['venue']}.")
    lines += ["", "Publisher BibTeX exports are retained for FedAvg, Fraboni, Krum, CGSV, ACE, Yin, FoolsGold, Deep Leakage from Gradients, A Little Is Enough and How To Backdoor Federated Learning. Official arXiv exports are retained for Wu, RFFL, Flower, DP-FedAvg, Fashion-MNIST and Lin's free-rider study. FLock, Witt, FLTrust, Rényi differential privacy, Practical Secure Aggregation, Tang's cross-silo mechanism, GTG-Shapley and Biscotti use publisher-deposited Crossref exports, checked against bibliographic records. The Krum export leaves pages empty; its page range was verified against DBLP. GTG-Shapley's article number was added to its page range from DBLP. No unread source is counted as verified.", ""]
    Path("docs/annotated_bibliography.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {len(entries)} annotations with {len(bibtex_keys)} uniquely matched BibTeX entries")


if __name__ == "__main__":
    main()
