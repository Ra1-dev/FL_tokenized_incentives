"""Render verified reading notes without claiming unread sources."""

import json
from pathlib import Path


def main():
    entries = json.loads(Path("results/literature/annotations.json").read_text(encoding="utf-8"))
    lines = ["# Annotated bibliography", "", "Generated by `python scripts/document_bibliography.py` from the source-reading manifest.",
             f"Current verified entries: {len(entries)}. This working bibliography is incomplete.", "",
             "| Source | Problem | Method | Data | Finding | What it does not do | Use in this project |", "|---|---|---|---|---|---|---|"]
    for e in entries:
        label = f"[{e['authors']} ({e['year']}), {e['title']}]({e['url']})"
        lines.append("| " + " | ".join([label] + [e[k] for k in ["problem", "method", "data", "finding", "missing", "use"]]) + " |")
    lines += ["", "## Reading and metadata provenance", ""]
    for e in entries:
        lines.append(f"- **{e['key']}**: {e['read']} Venue: {e['venue']}.")
    lines += ["", "Publisher BibTeX exports are retained for FedAvg, Fraboni, Krum, CGSV, ACE, Yin, FoolsGold, Deep Leakage from Gradients and A Little Is Enough. Official arXiv exports are retained for Wu, RFFL, Flower, DP-FedAvg, Fashion-MNIST and Lin's free-rider study. FLock, Witt, FLTrust, Rényi differential privacy, Practical Secure Aggregation and Tang's cross-silo mechanism use publisher-deposited Crossref exports, checked against bibliographic records. The Krum export leaves pages empty; its page range was verified against DBLP. No unread source is counted as verified.", ""]
    Path("docs/annotated_bibliography.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
